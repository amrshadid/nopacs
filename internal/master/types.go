// The bounds this package holds every value to. Input is hostile (rules,
// security): a value is bounded before it reaches a database, and a value past
// its bound is Invalid, never cut short.
const (
	// MaxIDLength bounds an id. Ids are opaque to the store; 64 bytes holds a
	// UUID in any of its spellings and a key id with room to spare.
	MaxIDLength = 64
	// MaxTenantNameLength is the longest tenant name: a name appears in URLs
	// and paths, and 63 is the longest DNS label, so a name can also be a
	// host name.
	MaxTenantNameLength = pathname.MaxNameLength
	// MaxDriverLength bounds the name of a database type, such as "sqlite".
	MaxDriverLength = 32
	// MaxSealedAddressLength bounds a tenant's sealed database address. An
	// address is a URL with a password; 16 KiB is far beyond any real one.
	MaxSealedAddressLength = 16 << 10
	// MaxStateReasonLength bounds the reason given with a tenant's state.
	MaxStateReasonLength = 1 << 10
	// KeyHashLength is the length of a key's hash: a SHA-256, made by package
	// secret.
	KeyHashLength = 32
	// MaxHolderLength bounds the name of a key's holder, in bytes: room for a
	// person's or a system's name, and no more text than that for a caller to
	// store in every key's row.
	MaxHolderLength = 256
	// MaxSettingNameLength bounds a setting's name.
	MaxSettingNameLength = 128
	// MaxSettingValueLength bounds a setting's value, in bytes.
	MaxSettingValueLength = 64 << 10
	// MaxAuditFieldLength bounds the short text fields of an audit entry: who,
	// the remote address, the method, the tenant name, the object and the
	// request id.
	MaxAuditFieldLength = 256
	// MaxAuditReasonLength bounds an audit entry's reason.
	MaxAuditReasonLength = 1 << 10
	// MaxAuditDetails bounds the number of pairs in an audit entry's details.
	MaxAuditDetails = 16
	// MaxAuditDetailKeyLength bounds a key of an audit entry's details.
	MaxAuditDetailKeyLength = 64
	// MaxAuditDetailValueLength bounds a value of an audit entry's details.
	MaxAuditDetailValueLength = 256
	// MaxAuditBatch bounds how many entries one AppendAudit takes, so one
	// call cannot hold the database's write lock for long.
	MaxAuditBatch = 10000
	// MaxPageLimit is the largest page a list returns.
	MaxPageLimit = 1000
)

// The keys AuditEntry.Details gets from SetGrant and RemoveGrant: the role a
// grant had before the change and the role it has after, "none" for no grant,
// so the audit log shows what a change of role replaced.
const (
	// DetailOldRole is the detail that holds the role a grant had before
	// SetGrant or RemoveGrant, or NoRole.
	DetailOldRole = "old_role"
	// DetailNewRole is the detail that holds the role a grant has after
	// SetGrant or RemoveGrant, or NoRole.
	DetailNewRole = "new_role"
	// NoRole is the value of DetailOldRole and DetailNewRole when there is
	// no grant on that side of the change.
	NoRole = "none"
)

// The keys SetTenantState and RevokeKey add to their audit entry's details,
// read inside the change, so that each of two concurrent calls on one row
// records what it saw.
const (
	// DetailOldState is the detail that holds the tenant's state before
	// SetTenantState.
	DetailOldState = "old_state"
	// DetailNewState is the detail that holds the tenant's state after
	// SetTenantState.
	DetailNewState = "new_state"
	// DetailAlreadyRevoked is the detail RevokeKey sets to "true" when the
	// key was revoked before the call, which then changed nothing, and to
	// "false" when this call revoked it.
	DetailAlreadyRevoked = "already_revoked"
)

// ErrDuplicateAuditID is in the chain of the error, of kind Internal, that a
// changing operation or AppendAudit returns when the audit entry's id is
// already taken. Ids are generated by the caller, so a duplicate is a bug,
// not a clash with the archive's state; it is told apart from a Conflict
// (a tenant name, tenant id or key id taken) with errors.Is, never by text.
var ErrDuplicateAuditID = errors.New("an audit entry with this id exists")

// TenantState says whether a tenant can be served.
type TenantState string

// The states of a tenant. A tenant that is not ready is refused on its own;
// the others keep working, so one database that is down or failed to upgrade
// does not take the installation with it.
const (
	// StateReady is a tenant whose database answers and is at the binary's
	// schema version.
	StateReady TenantState = "ready"
	// StateUnreachable is a tenant whose database does not answer.
	StateUnreachable TenantState = "unreachable"
	// StateUpgrading is a tenant whose database is being migrated.
	StateUpgrading TenantState = "upgrading"
	// StateFailed is a tenant that cannot be served until a person acts; the
	// reason says why.
	StateFailed TenantState = "failed"
	// StateMoved is a tenant an export handed to another installation: read
	// only, so nothing is written after the export's snapshot, until a
	// reclaim takes it back.
	StateMoved TenantState = "moved"
	// StateFenced is a tenant the owner record of one of its storages says
	// another installation (or a later generation) owns: every change is
	// refused, so two installations never write one storage, and no data is
	// served (FencedReadError), so what the new owner deletes or corrects is
	// not served on from this copy. The reason names the storage.
	StateFenced TenantState = "fenced"
)

// Valid reports whether s is one of the six states.
func (s TenantState) Valid() bool {
	switch s {
	case StateReady, StateUnreachable, StateUpgrading, StateFailed, StateMoved, StateFenced:
		return true
	}
	return false
}

// ReadOnly reports whether s is a state in which every change of a tenant
// is refused, while its database stays open: moved or fenced. A moved
// tenant's data is still served; a fenced one's is not (FencedReadError).
func (s TenantState) ReadOnly() bool { return s == StateMoved || s == StateFenced }

// ErrFencedRead is the cause of a read refused by a fenced tenant
// (FencedReadError), for errors.Is.
var ErrFencedRead = errors.New("a fenced tenant serves no data")

// FencedReadError returns the Precondition error of a read of its data
// (catalog, metadata, files, settings, audit, events) refused by the tenant
// named name, fenced for why (its state reason, which names the storage and
// the installation that owns it; may be empty). The message begins with
// ReasonTenantFenced, as the refusal of a change does. A fenced tenant
// serves no data: once another installation owns a storage, a delete, a
// relabel or a replace made there never reaches this installation's
// catalog, so serving from it would keep handing out what the owner
// withdrew, to keys the owner cannot revoke.
func FencedReadError(name, why string) error {
	msg := ReasonTenantFenced + ": the tenant " + name + " serves no data here, since another installation owns one of its storages"
	if why != "" {
		msg += " (" + why + ")"
	}
	return fault.Wrap(fault.Precondition, ErrFencedRead, msg)
}

// The reasons a change refused by a read-only tenant carries, as the API
// contract names them (access.proto, "precondition").
const (
	// ReasonTenantMoved is the reason of a change refused by a moved
	// tenant.
	ReasonTenantMoved = "TENANT_MOVED"
	// ReasonTenantFenced is the reason of a change refused by a fenced
	// tenant.
	ReasonTenantFenced = "TENANT_FENCED"
)

// ReadOnlyReason returns the reason a change refused by a tenant in state s
// carries, or "" when s is not read only.
func (s TenantState) ReadOnlyReason() string {
	switch s {
	case StateMoved:
		return ReasonTenantMoved
	case StateFenced:
		return ReasonTenantFenced
	}
	return ""
}

// ReadOnlyError returns the Precondition error of a change refused by the
// tenant named name, read only in state s for why (its state reason; may be
// empty). The message begins with the reason the contract names, so a
// person and a script both see which it is. A state that is not read only
// returns nil.
func ReadOnlyError(name string, s TenantState, why string) error {
	var msg string
	switch s {
	case StateMoved:
		msg = ReasonTenantMoved + ": the tenant " + name + " was handed to another installation by an export and is read only here; " +
			"a reclaim takes it back while no import has taken its storages over"
	case StateFenced:
		msg = ReasonTenantFenced + ": the tenant " + name + " is read only here, since another installation owns one of its storages"
	default:
		return nil
	}
	if why != "" {
		msg += " (" + why + ")"
	}
	return fault.New(fault.Precondition, msg)
}

// CheckStateChange returns a Precondition error unless by may change a
// tenant's state from old to next, a rule every driver applies in the
// change's transaction, to the state it reads there. A moved or fenced
// tenant stays read only whatever the server's own checks see of its
// database: the server (Server) may make a moved tenant fenced, and set a
// fenced one's reason again, and nothing else; taking a tenant out of
// either is a person's act (a reclaim, or the end of a failed export) made
// by a key or the local operator. The server giving back a failed export
// (ExportGiveBack) takes a moved tenant to ready and makes no other change
// of state: not a fenced tenant, which another installation's owner record
// holds, and not a ready one, which no export holds.
func CheckStateChange(old, next TenantState, by Actor) error {
	if by.IsExportGiveBack() {
		if old == StateMoved && next == StateReady {
			return nil
		}
		return fault.New(fault.Precondition, "the tenant is "+string(old)+": a failed export gives back only a moved tenant, made ready")
	}
	if !old.ReadOnly() || old == next || !by.IsServer() {
		return nil
	}
	if old == StateMoved && next == StateFenced {
		return nil
	}
	return fault.New(fault.Precondition, "the tenant is "+string(old)+": the server's own checks do not take it out of that state")
}

// Role is what a grant allows. Each role includes the ones before it, so a
// requirement is one comparison.
type Role string

// The roles.
const (
	RoleReader   Role = "reader"
	RoleWriter   Role = "writer"
	RoleOperator Role = "operator"
	RoleAdmin    Role = "admin"
)

// Valid reports whether r is one of the four roles. The empty role, which
// SetGrant returns when there was no grant before, is not valid in a grant.
func (r Role) Valid() bool {
	switch r {
	case RoleReader, RoleWriter, RoleOperator, RoleAdmin:
		return true
	}
	return false
}

// detail returns the role as it is written in an audit entry's details.
func (r Role) detail() string {
	if r == "" {
		return NoRole
	}
	return string(r)
}

// Outcome is how a request ended, as its audit entry records it.
type Outcome string

// The outcomes.
const (
	// OutcomeDone is a request that did what it asked.
	OutcomeDone Outcome = "done"
	// OutcomeRefused is a request the archive refused: no key, no grant, an
	// invalid argument.
	OutcomeRefused Outcome = "refused"
	// OutcomeFailed is a request that was allowed and did not succeed.
	OutcomeFailed Outcome = "failed"
)

// Valid reports whether o is one of the three outcomes.
func (o Outcome) Valid() bool {
	switch o {
	case OutcomeDone, OutcomeRefused, OutcomeFailed:
		return true
	}
	return false
}

// Tenant is one independent archive inside the installation, as the master
// knows it: its name and how to reach its database.
type Tenant struct {
	// ID is the tenant's opaque id, given by the caller.
	ID string
	// Name is 1 to 63 of a-z, 0-9 and "-", starting with a letter
	// (ValidateTenantName).
	Name string
	// Driver names the database type of the tenant's database.
	Driver string
	// SealedAddress is the tenant's database address as package secret
	// sealed it. The store keeps the bytes and never opens them.
	SealedAddress []byte
	// State says whether the tenant can be served.
	State TenantState
	// StateReason says why the tenant is in its state; it may be empty.
	StateReason string
	// Created is when the tenant was made.
	Created time.Time
}

// The database types a tenant's row may name (Tenant.Driver). They are here,
// beside the field they are values of, so a package that only names a type
// (the API's handlers) does not import the drivers and the database libraries
// behind them.
const (
	// SQLiteDriver is the name of the SQLite database type, as a tenant's
	// row in the master records it (Tenant.Driver).
	SQLiteDriver = "sqlite"

	// PostgresDriver is the name of the Postgres database type, as a
	// tenant's row in the master records it (Tenant.Driver).
	PostgresDriver = "postgres"
)

// Validate returns an Invalid error when t cannot be stored.
func (t Tenant) Validate() error {
	if err := ValidateID("tenant id", t.ID); err != nil {
		return err
	}
	if err := ValidateTenantName(t.Name); err != nil {
		return err
	}
	if t.Driver == "" || len(t.Driver) > MaxDriverLength || !allBytes(t.Driver, isLowerAlnum) {
		return invalid("a database type is 1 to " + strconv.Itoa(MaxDriverLength) + " of a-z and 0-9")
	}
	if len(t.SealedAddress) == 0 || len(t.SealedAddress) > MaxSealedAddressLength {
		return invalid("a sealed database address is 1 to " + strconv.Itoa(MaxSealedAddressLength) + " bytes")
	}
	if err := ValidateTenantState(t.State, t.StateReason); err != nil {
		return err
	}
	return ValidateTime("creation time", t.Created)
}

// ValidateTenantState returns an Invalid error unless state is one of the
// four and reason is UTF-8 of at most 1 KiB.
func ValidateTenantState(state TenantState, reason string) error {
	if !state.Valid() {
		return invalid("a tenant's state is ready, unreachable, upgrading or failed")
	}
	return validateText("state reason", reason, 0, MaxStateReasonLength)
}

// ValidateTenantName returns an Invalid error unless name is 1 to 63 of a-z,
// 0-9 and "-", starting with a letter, and is not a device name Windows
// reserves. A name appears in URLs and paths, so it is checked here, once,
// before it reaches either.
func ValidateTenantName(name string) error {
	if !pathname.WellFormedName(name) {
		return invalid("a tenant's name is 1 to 63 of a-z, 0-9 and -, starting with a letter")
	}
	if pathname.DeviceName(name) {
		return invalid("a tenant's name may not be con, prn, aux, nul, com0 to com9 or lpt0 to lpt9, which Windows reserves")
	}
	return nil
}

// Key is an API key as the master keeps it: its id and the hash of its
// secret, never the secret.
type Key struct {
	// ID is the key's public id, the part between "nopacs_" and the secret.
	ID string
	// Hash is the SHA-256 of the key's secret, made by package secret.
	Hash []byte
	// Holder names the person or system that holds the key: any UTF-8, at
	// most 256 bytes (MaxHolderLength).
	Holder string
	// Created is when the key was made.
	Created time.Time
	// Expires is when the key stops working; the zero time is never.
	Expires time.Time
	// LastUsed is when the key was last used, to within a minute; the zero
	// time is never.
	LastUsed time.Time
	// Revoked is when the key was revoked; the zero time is not revoked.
	Revoked time.Time
	// Rules is where the key may be used from.
	Rules KeyRules
	// LastAddress is the caller's address at the use LastUsed records:
	// written with it, so it is as old as that time; empty when the key has
	// never been used off the local socket.
	LastAddress string
	// Successor is the id of the key a rotation replaced this one with;
	// empty when it was never rotated. A key is rotated at most once.
	Successor string
	// Suspended is when the key was suspended; the zero time is not
	// suspended. A suspended key is refused as no good until the local
	// operator reinstates it: a restore suspends every key it brings back,
	// since a key revoked, or a grant removed, after the backup was made
	// would otherwise work again.
	Suspended time.Time
	// Masked says the key is never answered a value that is not in its
	// archived, de-identified form: what an AI agent or another outside
	// service holds, whose output leaves the site. It is set when the key
	// is made, carried to the key a rotation makes, and never cleared, so
	// a key handed to such a service cannot be widened afterward; a key
	// without it is made in its place.
	Masked bool
}

// Validate returns an Invalid error when k cannot be created. A new key has
// never been used and is not revoked, so those two times must be zero.
func (k Key) Validate() error {
	if err := ValidateID("key id", k.ID); err != nil {
		return err
	}
	if len(k.Hash) != KeyHashLength {
		return invalid("a key's hash is " + strconv.Itoa(KeyHashLength) + " bytes")
	}
	if err := validateText("holder", k.Holder, 1, MaxHolderLength); err != nil {
		return err
	}
	if err := ValidateTime("creation time", k.Created); err != nil {
		return err
	}
	if !k.Expires.IsZero() {
		if err := ValidateTime("expiry", k.Expires); err != nil {
			return err
		}
		if !k.Expires.After(k.Created) {
			return invalid("a key's expiry is after its creation")
		}
	}
	if !k.LastUsed.IsZero() || !k.Revoked.IsZero() || k.LastAddress != "" || k.Successor != "" || !k.Suspended.IsZero() {
		return invalid("a new key has not been used, revoked, rotated or suspended")
	}
	return k.Rules.Validate()
}

// Scope is what a grant applies to: one tenant, or the installation. The zero
// Scope is the installation.
type Scope struct {
	// TenantID is the tenant's id, or empty for the installation.
	TenantID string
}

// Installation is the scope of the whole installation.
var Installation = Scope{}

// TenantScope returns the scope of one tenant.
func TenantScope(tenantID string) Scope {
	return Scope{TenantID: tenantID}
}

// IsInstallation reports whether s is the installation.
func (s Scope) IsInstallation() bool {
	return s.TenantID == ""
}

// Validate returns an Invalid error when s names a tenant with an id that is
// not valid.
func (s Scope) Validate() error {
	if s.IsInstallation() {
		return nil
	}
	return ValidateID("tenant id", s.TenantID)
}

// String returns "installation" or "tenant/<id>", as the scope is written in
// an audit entry's details.
func (s Scope) String() string {
	if s.IsInstallation() {
		return "installation"
	}
	return "tenant/" + s.TenantID
}

// Roles is what RolesFor reads for a key and a tenant name: the key's role
// on the installation, the tenant the name belongs to, and the key's role on
// it. A role is the empty Role when the key holds none.
type Roles struct {
	// Installation is the key's role on the installation.
	Installation Role
	// Tenant is the key's role on the tenant named; empty when the tenant
	// was not found.
	Tenant Role
	// TenantID is the id of the tenant named, at the time of the read;
	// empty when it was not found.
	TenantID string
	// TenantFound reports whether a tenant has the name asked for.
	TenantFound bool
}

// Grant gives a key a role on one scope. A key has at most one grant per
// scope, so its role there is never ambiguous and setting a grant again
// replaces the role.
type Grant struct {
	// KeyID is the id of the key the grant is for.
	KeyID string
	// Scope is what the grant applies to: one tenant, by id, or the
	// installation. The id, not the name, is the grant's identity.
	Scope Scope
	// Role is what the grant allows.
	Role Role
	// TenantName is the name of the scope's tenant at the time of the read,
	// filled in by the lists so a caller that shows names needs no read of
	// its own per tenant. It is empty for the installation, and ignored by
	// SetGrant.
	TenantName string
}

// Validate returns an Invalid error when g cannot be stored.
func (g Grant) Validate() error {
	if err := ValidateID("key id", g.KeyID); err != nil {
		return err
	}
	if err := g.Scope.Validate(); err != nil {
		return err
	}
	if !g.Role.Valid() {
		return invalid("a role is reader, writer, operator or admin")
	}
	return nil
}

// ErrGrantBound is in the chain of a change of a grant refused because a
// tenant's admin made it past what a tenant's admin may do
// (CheckGrantChange).
var ErrGrantBound = errors.New("a tenant's admin may not make this change of a grant")

// CheckGrantChange returns a Denied error, ErrGrantBound in its chain,
// unless by may change the grant of the key keyID on scope from old to next
// (next empty for a removal; old empty when there was none); onInstallation
// is that key's role on the installation (empty for none). A store calls
// it inside the change's transaction, after it read both roles, so a role
// another change set meanwhile is judged too.
//
// A key acting by its admin grant on a tenant (a tenant's admin) changes
// grants on that tenant only, at reader, writer or operator; never its own
// key's; never a key that is admin there, nor one that is admin on the
// installation, which outranks it. Making or removing a tenant's admin
// stays with the installation's admin, so a tenant's admin cannot multiply
// admins or remove one, nor raise its own role, nor lower or shut out an
// installation's admin. Any other actor (a key acting by its grant on the
// installation, the local operator, the server) is held to the store's
// other rules only.
func CheckGrantChange(by Actor, keyID string, scope Scope, old, next, onInstallation Role) error {
	if !by.IsKey() || by.Scope().IsInstallation() {
		return nil
	}
	deny := func(why string) error { return fault.Wrap(fault.Denied, ErrGrantBound, why) }
	switch {
	case scope.IsInstallation() || scope.TenantID != by.Scope().TenantID:
		return deny("a tenant's admin changes grants on that tenant only")
	case keyID == by.KeyID():
		return deny("a tenant's admin does not change its own key's grant")
	case next == RoleAdmin:
		return deny("a tenant's admin gives reader, writer or operator; an admin of a tenant is made by the installation's admin")
	case old == RoleAdmin:
		return deny("a tenant's admin does not change or remove the grant of a key that is admin on the tenant")
	case onInstallation == RoleAdmin:
		return deny("a tenant's admin does not change or remove the grant of a key that is admin on the installation")
	}
	return nil
}

// Setting is one installation setting.
type Setting struct {
	// Name is 1 to 128 of a-z, 0-9, ".", "_" and "-".
	Name string
	// Value is UTF-8 of at most 64 KiB; the empty string is a value.
	Value string
}

// ValidateSettingName returns an Invalid error unless name is 1 to 128 of
// a-z, 0-9, ".", "_" and "-".
func ValidateSettingName(name string) error {
	if name == "" || len(name) > MaxSettingNameLength ||
		!allBytes(name, func(b byte) bool { return isLowerAlnum(b) || b == '.' || b == '_' || b == '-' }) {
		return invalid("a setting's name is 1 to 128 of a-z, 0-9, ., _ and -")
	}
	return nil
}

// ValidateSettingValue returns an Invalid error unless value is UTF-8 of at
// most 64 KiB.
func ValidateSettingValue(value string) error {
	return validateText("setting value", value, 0, MaxSettingValueLength)
}

// Page asks for one page of a list: up to Limit items after the one Cursor
// points at. The empty cursor is the start of the list.
type Page struct {
	// Cursor is the next cursor a previous page returned, or empty.
	Cursor string
	// Limit is how many items to return, 1 to 1000.
	Limit int
}

// Validate returns an Invalid error unless the limit is 1 to 1000. A cursor
// is checked by the store that made it, since only it can read one.
func (p Page) Validate() error {
	if p.Limit < 1 || p.Limit > MaxPageLimit {
		return invalid("a page's limit is 1 to " + strconv.Itoa(MaxPageLimit))
	}
	return nil
}
