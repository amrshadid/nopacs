// Command refdocs writes the reference pages of docs/reference from the code
// that defines what they list: the settings catalog, the command trees, the
// error kinds and codes, the event types of the contract, the metrics a
// running server exposes and the environment variables the programs read.
//
// A reference page that a person types drifts from the program it describes;
// one the program's own definitions produce cannot say what the program does
// not do. With -check the command writes nothing and exits 1, naming each
// page whose committed text differs from what the code produces, so a gate can
// refuse a change that leaves a page behind.
//
// Usage, from the repository root:
//
//	go run ./internal/testkit/cmd/refdocs [-check] [-root DIR]
//
// It is a test-only program: nothing the server or the command line runs
// imports it.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// page is one generated file of docs/reference.
type page struct {
	// file is the page's name inside docs/reference.
	file string
	// title is its first heading.
	title string
	// source says, in a few words, what the page is made from.
	source string
	// render returns the page's body, after the heading, for the repository
	// at root.
	render func(root string) (string, error)
}

// pages lists every generated page in the order docs/reference/README.md names
// them.
func pages() []page {
	return []page{
		{"settings.md", "Settings reference", "the settings catalog", renderSettings},
		{"commands.md", "Command reference", "the command trees of nopacs and nopacs-server", renderCommands},
		{"errors.md", "Error kinds and codes", "the error kinds, their API codes and exit codes", renderErrors},
		{"events.md", "Event types", "the contract's event types", renderEvents},
		{"metrics.md", "Metrics", "the metrics a running server exposes at /metrics", renderMetrics},
		{"environment.md", "Environment variables", "the variables the programs, tests and scripts read", renderEnvironment},
	}
}

// header is the first line of every generated page: it says the page is
// generated and by which make target, so nobody edits it by hand.
const header = "> Generated by `make docs` from %s. Do not edit it by hand: `make check-docs` fails when it differs from what the code produces.\n\n"

// build returns the whole text of p.
func build(root string, p page) ([]byte, error) {
	body, err := p.render(root)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", p.file, err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, header, p.source)
	fmt.Fprintf(&b, "# %s\n\n", p.title)
	b.WriteString(strings.TrimRight(body, "\n"))
	b.WriteString("\n")
	return b.Bytes(), nil
}

// run is the whole program, with its arguments and streams passed in so a
// test can drive it. It returns the exit status: 0 done, 1 a page differs
// (with -check) or could not be made, 2 a usage mistake.
func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("refdocs", flag.ContinueOnError)
	fs.SetOutput(stderr)
	check := fs.Bool("check", false, "write nothing; exit 1 and name each page that differs from what the code produces")
	root := fs.String("root", ".", "the repository's root")
	serveChild := fs.String("serve-child", "", "internal: serve the installation in this data directory, for the metrics page")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *serveChild != "" {
		return serveForMetrics(*serveChild)
	}
	if fs.NArg() != 0 {
		fmt.Fprintln(stderr, "refdocs: no arguments are taken")
		return 2
	}
	return generate(*root, pages(), *check, stdout, stderr)
}

// generate writes each page of ps under root/docs/reference, or with check
// compares it with the committed file and writes nothing.
func generate(root string, ps []page, check bool, stdout, stderr io.Writer) int {
	dir := filepath.Join(root, "docs", "reference")
	status := 0
	for _, p := range ps {
		want, err := build(root, p)
		if err != nil {
			fmt.Fprintln(stderr, "refdocs:", err)
			status = 1
			continue
		}
		path := filepath.Join(dir, p.file)
		if check {
			have, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(have, want) {
				fmt.Fprintf(stderr, "refdocs: %s differs from what the code produces; run make docs\n", filepath.ToSlash(filepath.Join("docs", "reference", p.file)))
				status = 1
			}
			continue
		}
		if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // G301: documentation, read by everyone.
			fmt.Fprintln(stderr, "refdocs:", err)
			return 1
		}
		if err := os.WriteFile(path, want, 0o644); err != nil { //nolint:gosec // G306: documentation, read by everyone.
			fmt.Fprintln(stderr, "refdocs:", err)
			status = 1
			continue
		}
		fmt.Fprintf(stdout, "wrote docs/reference/%s\n", p.file)
	}
	if check && status == 0 {
		fmt.Fprintln(stdout, "check-docs: every generated page matches the code")
	}
	return status
}

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

// cell makes text safe inside a Markdown table cell: a pipe would end the
// cell and a line break would end the row.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.TrimSpace(s)
}
