// TestSettingBoundsHoldInTheCatalog guards the ranges the settings page prints:
// each setting's own rule must accept the least and the most the page names
// and refuse the value just outside each, so the page cannot print a bound the
// server does not hold.
func TestSettingBoundsHoldInTheCatalog(t *testing.T) {
	t.Parallel()
	table := settings.MustBuiltin()
	for name, b := range settingBounds {
		def, ok := table.Lookup(name)
		if !ok {
			t.Errorf("%s: no such setting", name)
			continue
		}
		for i, v := range b {
			if v == "" {
				continue
			}
			err := def.Validate(v)
			inside := i == 1 || i == 2
			if inside && err != nil {
				t.Errorf("%s: %q is a bound of the page, and the setting refuses it: %v", name, v, err)
			}
			if !inside && err == nil {
				t.Errorf("%s: %q is outside the bounds of the page, and the setting accepts it", name, v)
			}
		}
	}
}

// TestEveryDefaultIsShownAsTheCatalogHasIt guards the settings page against
// dropping a setting: every built-in setting is a row, with its default.
func TestEveryDefaultIsShownAsTheCatalogHasIt(t *testing.T) {
	t.Parallel()
	text, err := renderSettings("")
	if err != nil {
		t.Fatal(err)
	}
	for _, d := range settings.Builtin() {
		row := "| `" + d.Name + "` |"
		i := strings.Index(text, row)
		if i < 0 {
			t.Errorf("%s has no row", d.Name)
			continue
		}
		line, _, _ := strings.Cut(text[i:], "\n")
		want := "empty"
		if d.Default != "" {
			want = "`" + d.Default + "`"
		}
		if !strings.Contains(line, "| "+want+" |") {
			t.Errorf("%s: the row does not show the default %s: %s", d.Name, want, line)
		}
	}
}

// TestEnumComments guards the reading of a contract's enum: a comment of
// several lines above a value joins into one sentence, and a value after a
// blank line gets none of the one before.
func TestEnumComments(t *testing.T) {
	t.Parallel()
	proto := "enum Other {\n  OTHER_A = 0;\n}\n\nenum Kind {\n  // Never answered.\n  KIND_UNSPECIFIED = 0;\n\n  // One line\n  // and another.\n  KIND_A = 1;\n}\n"
	got, err := enumComments(proto, "Kind")
	if err != nil {
		t.Fatal(err)
	}
	if got["KIND_A"] != "One line and another." || got["KIND_UNSPECIFIED"] != "Never answered." || len(got) != 2 {
		t.Fatalf("comments = %#v", got)
	}
	if _, err := enumComments(proto, "Missing"); err == nil {
		t.Fatal("an enum the file does not hold was found")
	}
}

// TestCheckNamesTheDifferingPage guards the gate: written pages pass the
// check, and a page edited by hand fails it, named, with nothing rewritten.
func TestCheckNamesTheDifferingPage(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	ps := []page{
		{"settings.md", "One", "a test", func(string) (string, error) { return "first\n", nil }},
		{"errors.md", "Two", "a test", func(string) (string, error) { return "second\n", nil }},
	}
	var out, errs bytes.Buffer
	if code := generate(root, ps, false, &out, &errs); code != 0 {
		t.Fatalf("write exited %d: %s", code, errs.String())
	}
	out.Reset()
	if code := generate(root, ps, true, &out, &errs); code != 0 || !strings.Contains(out.String(), "matches the code") {
		t.Fatalf("check of fresh pages exited %d: %s%s", code, out.String(), errs.String())
	}
	two := filepath.Join(root, "docs", "reference", "errors.md")
	edited := []byte("> Generated by hand\n")
	if err := os.WriteFile(two, edited, 0o644); err != nil { //nolint:gosec // G306: a page of documentation in a test's own directory.
		t.Fatal(err)
	}
	errs.Reset()
	if code := generate(root, ps, true, &out, &errs); code != 1 {
		t.Fatalf("check of an edited page exited %d, want 1", code)
	}
	if !strings.Contains(errs.String(), "docs/reference/errors.md differs") || strings.Contains(errs.String(), "settings.md") {
		t.Fatalf("the check named the wrong pages: %q", errs.String())
	}
	if got, _ := os.ReadFile(two); !bytes.Equal(got, edited) {
		t.Fatal("the check rewrote the page")
	}
	first, _ := os.ReadFile(filepath.Join(root, "docs", "reference", "settings.md"))
	if !strings.HasPrefix(string(first), "> Generated by `make docs` from a test.") {
		t.Fatalf("a page does not start by saying it is generated: %q", first)
	}
}
